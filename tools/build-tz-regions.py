"""Build public/deck/tz-regions.js: the 31 regions of Tanzania as plain shapes for the Annual Rep deck's maps.

Why it is built, not downloaded: the open region-level boundary sets (geoBoundaries ADM1, Natural Earth) are the
2015 map, 30 regions, with no Songwe (created January 2016 from the west of Mbeya). The district-level set from the
Tanzania National Bureau of Statistics / UN OCHA ROSA (2021, in geoBoundaries as ADM2, CC BY 3.0 IGO) does have Songwe's
five districts, so regions are made by merging districts: each district goes to the 2015 region it overlaps most, and
Ileje, Mbozi, Momba, Songwe and Tunduma go to Songwe instead of Mbeya.

  pip install shapely
  B=https://media.githubusercontent.com/media/wmgeolab/geoBoundaries/main/releaseData/gbOpen/TZA
  curl -o adm1.geojson $B/ADM1/geoBoundaries-TZA-ADM1_simplified.geojson
  curl -o adm2.geojson $B/ADM2/geoBoundaries-TZA-ADM2_simplified.geojson
  python3 tools/build-tz-regions.py adm1.geojson adm2.geojson public/deck/tz-regions.js

(media.githubusercontent.com, not raw.githubusercontent.com: these files are Git LFS.) The output is checked by
test/annualppt.test.mjs: 31 regions, the five of Zanzibar and Songwe among them, every shape inside Tanzania.
"""
import json, sys
from shapely.geometry import shape, MultiPolygon
from shapely.ops import unary_union, polylabel
from shapely.validation import make_valid

adm1_path, adm2_path, out_path = sys.argv[1:4]
SONGWE = {'Ileje', 'Mbozi', 'Momba', 'Songwe', 'Tunduma'}
RENAME = {'North Pemba': 'Kaskazini Pemba', 'South Pemba': 'Kusini Pemba', 'Zanzibar North': 'Kaskazini Unguja',
          'Zanzibar South & Central': 'Kusini Unguja', 'Zanzibar Urban/West': 'Mjini Magharibi'}
TOL, MIN_AREA = 0.018, 0.0012          # simplify to about 2 km; drop specks (never a region's biggest piece)

old = [(f['properties']['shapeName'], make_valid(shape(f['geometry']))) for f in json.load(open(adm1_path))['features']]
districts = {f['properties']['shapeName']: make_valid(shape(f['geometry'])) for f in json.load(open(adm2_path))['features']}

regions = {}
for name, g in districts.items():
    best = max(old, key=lambda o: g.intersection(o[1]).area)[0]
    regions.setdefault('Songwe' if best == 'Mbeya' and name in SONGWE else best, []).append(name)
assert len(regions) == 31, 'expected 31 regions, got %d' % len(regions)

out = []
for reg in sorted(regions, key=lambda r: RENAME.get(r, r)):
    u = unary_union([districts[n] for n in regions[reg]]).buffer(0)
    pieces = sorted(u.geoms if isinstance(u, MultiPolygon) else [u], key=lambda p: -p.area)
    rings, biggest = [], None
    for p in pieces:
        if p.area < MIN_AREA and rings:
            continue
        s = p.simplify(TOL, preserve_topology=True)
        for q in (s.geoms if isinstance(s, MultiPolygon) else [s]):
            xy = list(q.exterior.coords)[:-1]
            if len(xy) >= 3:
                rings.append([int(round(v * 100)) for pt in xy for v in pt])
                biggest = biggest or q
    lp = polylabel(biggest, tolerance=0.01)
    out.append({'n': RENAME.get(reg, reg), 'c': [round(lp.x, 2), round(lp.y, 2)], 'g': rings})

header = """/* tz-regions -- the 31 regions of Tanzania (26 Mainland, 5 Zanzibar) as plain shapes, for the Annual Rep deck's maps.
   GENERATED by tools/build-tz-regions.py, do not edit by hand. Built by merging the 170 districts of the Tanzania National Bureau of Statistics / UN OCHA ROSA
   administrative boundaries (2021, in which Songwe Region, created in January 2016 from the west of Mbeya, is its own region of five
   districts: Ileje, Mbozi, Momba, Songwe, Tunduma) as published in geoBoundaries (gbOpen, ADM2), licence CC BY 3.0 IGO.
   Each district sits in the region it overlaps most; the five districts of Songwe are taken out of Mbeya. Merged per region, simplified
   to about 2 km (invisible at slide size), holes dropped. Coordinates are lon and lat in hundredths of a degree, flat x,y pairs, one
   array per piece (islands are pieces); `c` is the label point, inside the biggest piece. */
"""
open(out_path, 'w', encoding='utf-8').write(header + "var ANPPT_TZ = { attribution: 'Boundaries: Tanzania National Bureau of Statistics / UN OCHA ROSA (2021), via geoBoundaries, CC BY 3.0 IGO', regions: "
                                            + json.dumps(out, separators=(',', ':')) + " };\n")
print('wrote', out_path, len(out), 'regions', sum(len(r) // 2 for o in out for r in o['g']), 'points')
